    title, _, rest = p.partition("\n")
    if "- «" not in rest: continue
    title = re.sub(r"^درس \d+:\s*", "", title).replace(" — بلفظ الكتاب", "")
    items = "\n".join(l for l in rest.splitlines() if l.startswith("- «"))
    notes.append(f"## {title}\n\n{items}\n")
